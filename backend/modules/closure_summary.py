"""
Closure summary for a closed case: who, what and how, with the guilty details.

This only ASSEMBLES what the investigator and the evidence already hold:
  * who        - people the investigator designated (guilty first), with the written basis,
                 who designated them and when, their IDs / photos / supporting observations
  * what / how - evidence observations that mention the guilty person, the items, vehicles and
                 identifiers found in the case, and the dated sequence of events
Nothing here is a finding of guilt by the system. The guilty designation is the investigator's
own determination and is shown as such. No text is generated by a model.
"""
from __future__ import annotations

import re
from typing import Any, Dict, List

_SUSPECT_ROLES = ("SUSPECT", "PERSON_OF_INTEREST")


def _name_words(person: Dict[str, Any]) -> List[str]:
    """Distinctive words (3+ letters) from the person's name, aliases and alias norms."""
    raw = [person.get("name") or ""] + list(person.get("aliases") or []) + list(person.get("alias_norms") or [])
    words = {w for r in raw for w in re.findall(r"[a-z]{3,}", r.lower())}
    return sorted(words - {"the", "and", "tier", "visitor", "unknown"})


def _mentions(text: str, words: List[str]) -> bool:
    low = (text or "").lower()
    return any(re.search(rf"\b{re.escape(w)}\b", low) for w in words)


def _brief(p: Dict[str, Any]) -> Dict[str, Any]:
    return {"key": p["key"], "name": p["name"], "role": p.get("role"),
            "designated_by": (p.get("designation") or {}).get("by"),
            "designated_at": (p.get("designation") or {}).get("at")}


def build_closure_summary(case: Dict[str, Any], findings: Dict[str, Any], timeline: Dict[str, Any],
                          citizen_links: Dict[str, List[Dict[str, Any]]]) -> Dict[str, Any]:
    people = findings.get("people", [])
    guilty = [p for p in people if p.get("role") == "GUILTY"]
    events = timeline.get("events", [])

    guilty_out = []
    for p in guilty:
        words = _name_words(p)
        # observations in other evidence that mention this person, in time order when dated
        mentions = [e for e in events if _mentions(e.get("text", ""), words)]
        mentions.sort(key=lambda e: (e.get("offset_ms") is None, e.get("offset_ms") or 0))
        guilty_out.append({
            "key": p["key"], "name": p["name"], "aliases": p.get("aliases", []),
            "basis": (p.get("designation") or {}).get("basis"),
            "designated_by": (p.get("designation") or {}).get("by"),
            "designated_at": (p.get("designation") or {}).get("at"),
            "identifiers": p.get("identifiers", []),
            "photos": p.get("photos", [])[:4],
            "support": p.get("support", [])[:10],
            "what_the_evidence_shows": [
                {"file_name": e["file_name"], "kind": e.get("label"), "time": e.get("time"),
                 "assumed_date": e.get("assumed_date"), "text": e["text"], "ref": e.get("ref")}
                for e in mentions[:12]],
            "citizen": citizen_links.get(p["key"]),
        })

    # the means and trail: what was used and how it can be traced
    how = {
        "items": [{"name": i.get("display") or i.get("name"), "item_class": i.get("item_class"),
                   "verified": i.get("verified"), "files": i.get("evidence_count"),
                   "photo": (i.get("photos") or [{}])[0].get("url")} for i in findings.get("items", [])[:12]],
        "vehicles": [{"description": v.get("display") or v.get("description"), "plates": v.get("plates", []),
                      "verified": v.get("verified"), "files": v.get("evidence_count"),
                      "photo": (v.get("photos") or [{}])[0].get("url")} for v in findings.get("vehicles", [])[:8]],
        "identifiers": [{"value": i["value"], "verified": i.get("verified"), "files": i.get("evidence_count"),
                         "label": i.get("label")} for i in findings.get("ids", [])[:12]],
    }

    sequence = [{"file_name": e["file_name"], "kind": e.get("label"), "time": e.get("time"),
                 "assumed_date": e.get("assumed_date"), "text": e["text"]}
                for e in sorted((e for e in events if e.get("time")), key=lambda e: e.get("offset_ms") or 0)[:20]]

    notes = []
    if not guilty:
        notes.append("No one was designated as guilty on this case. Open the investigation board, People tab, to record "
                     "the investigator's determination before relying on this summary.")
    elif any(not (g["basis"] or "").strip() for g in guilty_out):
        notes.append("A guilty designation has no written basis.")

    return {
        "case": {k: case.get(k) for k in ("id", "case_number", "title", "description", "status", "created_at", "updated_at")},
        "guilty": guilty_out,
        "others": {
            "victims": [_brief(p) for p in people if p.get("role") == "VICTIM"],
            "suspects": [_brief(p) for p in people if p.get("role") in _SUSPECT_ROLES],
            "witnesses": [_brief(p) for p in people if p.get("role") == "WITNESS"],
            "cleared": [_brief(p) for p in people if p.get("role") == "CLEARED"],
        },
        "how": how,
        "sequence": sequence,
        "notes": notes,
        "notice": ("Compiled from the evidence and the investigator's own designations. The guilty designation is "
                   "the investigator's determination, not a finding of this system."),
    }
